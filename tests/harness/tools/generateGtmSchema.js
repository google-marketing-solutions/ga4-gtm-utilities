#!/usr/bin/env node
/**
 * @fileoverview Regenerates tests/harness/gtmSchema.js from the public Tag
 * Manager API v2 discovery document, so the fake API can reject unknown
 * fields and invalid enum values exactly where the real API would.
 *
 * Usage:
 *   node tests/harness/tools/generateGtmSchema.js            # downloads with curl
 *   node tests/harness/tools/generateGtmSchema.js disc.json  # uses a local copy
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const {execFileSync} = require('node:child_process');

const DISCOVERY_URL = 'https://tagmanager.googleapis.com/$discovery/rest?version=v2';
const ROOTS = ['Tag', 'Trigger', 'Variable', 'Folder', 'Client', 'Transformation', 'CustomTemplate',
  'Zone', 'GtagConfig', 'BuiltInVariable', 'Workspace', 'Container', 'Account', 'Destination', 'Entity',
  'ProposedChange'];

const source = process.argv[2];
const text = source ? fs.readFileSync(source, 'utf8') :
  execFileSync('curl', ['-sS', '--max-time', '60', DISCOVERY_URL], {encoding: 'utf8', maxBuffer: 64 * 1024 * 1024});
const discovery = JSON.parse(text);

const out = {};
const queue = [...ROOTS];
while (queue.length) {
  const name = queue.shift();
  if (out[name]) continue;
  const schema = discovery.schemas[name];
  if (!schema) throw new Error(`schema ${name} not found in discovery document`);
  const fields = {};
  for (const [key, prop] of Object.entries(schema.properties || {})) {
    let spec;
    if (prop.$ref) {
      spec = {ref: prop.$ref};
      queue.push(prop.$ref);
    } else if (prop.type === 'array') {
      if (prop.items.$ref) {
        spec = {arrayOf: prop.items.$ref};
        queue.push(prop.items.$ref);
      } else {
        spec = {array: prop.items.type};
        if (prop.items.enum) spec.enum = prop.items.enum;
      }
    } else {
      spec = {type: prop.type};
      if (prop.enum) spec.enum = prop.enum;
    }
    fields[key] = spec;
  }
  out[name] = fields;
}

const sorted = Object.fromEntries(Object.keys(out).sort().map((k) => [k, out[k]]));
const body = `/**
 * @fileoverview GENERATED by tools/generateGtmSchema.js from the Tag Manager
 * API v2 discovery document (revision ${discovery.revision}). Do not edit by hand.
 *
 * Per schema: field -> {type, enum?} | {ref} | {arrayOf} | {array, enum?}.
 */
'use strict';

/* eslint-disable */
const GTM_SCHEMAS = ${JSON.stringify(sorted)};

module.exports = {GTM_SCHEMAS, GTM_DISCOVERY_REVISION: ${JSON.stringify(discovery.revision)}};
`;
const target = path.join(__dirname, '..', 'gtmSchema.js');
fs.writeFileSync(target, body);
console.log(`wrote ${target} (${Object.keys(sorted).length} schemas, revision ${discovery.revision})`);
